#!/usr/bin/env node
// Regenerate MAP.md, the vault's table of contents, from note frontmatter.
//
// Plain extraction only, no model: for every note it reads the frontmatter (title, type,
// status, pillar, stage) plus the first line of prose, and writes one line per note grouped
// by folder. The result is a file a person or an agent reads once to know what exists and
// where, which is what lets this vault work without a search index.
//
// Usage: node bin/index.mjs [vault-root]
import fs from 'node:fs';
import path from 'node:path';
import { noteDirs, notesIn, parseNote, listValue, firstProseLine, vaultRoot, ENTITY_DIRS } from './lib-vault.mjs';

// What each folder holds, for the heading above its notes. A folder that is not listed is a
// life area, so a renamed or added one needs no change here.
const FOLDER_BLURB = {
  projects: 'one note per initiative (`stage:` says whether it is being worked)',
  people: 'one note per person',
  decisions: 'one note per decision',
  meetings: 'dated meetings (the filename starts with the date)',
  reviews: 'weekly and monthly reviews',
  journal: 'daily capture notes (transient until swept)',
  sources: 'one note per ingested raw file (the provenance layer)',
};

const MAX_LINE = 110;
const root = vaultRoot(process.argv.slice(2));

const truncate = (s, n) => (s.length <= n ? s : `${s.slice(0, n - 1).trimEnd()}…`);

function lineFor(rel, fields, body) {
  const name = path.basename(rel, '.md');
  const bits = [];
  if (fields.stage) bits.push(fields.stage);
  if (fields.status && fields.status !== 'current') bits.push(fields.status);
  const dir = rel.split(/[/\\]/)[0];
  if (ENTITY_DIRS.includes(dir)) bits.push(...listValue(fields.pillar));
  const tag = bits.length ? ` (${bits.join(', ')})` : '';
  const prose = firstProseLine(body);
  const head = `- [[${name}]]${tag}`;
  return prose ? truncate(`${head} - ${prose}`, MAX_LINE) : head;
}

const dirs = noteDirs(root);
const out = [];
const byType = {};
const byPillar = {};
let total = 0;

for (const dir of dirs) {
  const notes = notesIn(root, dir);
  const lines = [];
  for (const rel of notes) {
    const { fields, body } = parseNote(fs.readFileSync(path.join(root, rel), 'utf8'));
    lines.push(lineFor(rel, fields, body));
    const t = fields.type || 'unknown';
    byType[t] = (byType[t] || 0) + 1;
    for (const p of listValue(fields.pillar)) byPillar[p] = (byPillar[p] || 0) + 1;
    total += 1;
  }
  const kind = FOLDER_BLURB[dir] || 'a life area: topic notes';
  out.push(`## \`${dir}/\` - ${kind} (${lines.length})`, '');
  out.push(...(lines.length ? lines : ['_(empty)_']), '');
}

const tally = (o) => Object.keys(o).sort().map((k) => `${k} ${o[k]}`).join(', ') || 'none yet';
const header = [
  '# MAP - every note in the vault, one line each',
  '',
  'Generated by `bin/index.mjs` from each note\'s frontmatter plus its first line of prose.',
  'Do not edit by hand: regenerate it after a batch of changes, or let `bin/housekeeping.mjs`',
  'do it. Read `START-HERE.md` first for how the vault is organised, use this file to find a',
  'note, then `rg` for anything inside it.',
  '',
  `**${total} notes.** By type: ${tally(byType)}. By life area: ${tally(byPillar)}.`,
  '',
  'Legend: `(stage)` on a project is `idea|active|on-hold|done`, `(status)` is shown only when',
  'it is not `current`, and entity notes show their life area.',
  '',
];

fs.writeFileSync(path.join(root, 'MAP.md'), `${[...header, ...out].join('\n').replace(/\n+$/, '')}\n`);
console.log(`MAP.md: ${total} notes across ${dirs.length} folders`);
